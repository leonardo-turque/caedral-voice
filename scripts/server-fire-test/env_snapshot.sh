#!/usr/bin/env bash
# Environment snapshot for the server fire-test report (read-only).
echo "{"
echo "\"hostname\": \"$(hostname)\","
echo "\"kernel\": \"$(uname -r)\","
echo "\"uptime_s\": $(awk '{print $1}' /proc/uptime),"
echo "\"os\": \"$(grep PRETTY_NAME /etc/os-release | cut -d'"' -f2)\","
echo "\"cpu_model\": \"$(lscpu | grep 'Model name' | sed 's/Model name: *//')\","
echo "\"cpus_logical\": $(nproc),"
echo "\"load_avg\": \"$(cat /proc/loadavg | cut -d' ' -f1-3)\","
echo "\"mem_total_mb\": $(free -m | awk '/^Mem:/{print $2}'),"
echo "\"mem_available_mb\": $(free -m | awk '/^Mem:/{print $7}'),"
echo "\"swap_total_mb\": $(free -m | awk '/^Swap:/{print $2}'),"
echo "\"swap_used_mb\": $(free -m | awk '/^Swap:/{print $3}'),"
echo "\"disk_root_pct\": \"$(df -h / | awk 'NR==2{print $5}')\","
echo "\"disk_root_free\": \"$(df -h / | awk 'NR==2{print $4}')\","
echo "\"docker_version\": \"$(docker --version | awk '{print $3}' | tr -d ,)\","
echo "\"compose_version\": \"$(docker compose version --short 2>/dev/null)\","
echo "\"containers_running\": $(docker ps -q | wc -l),"
echo "\"containers_total\": $(docker ps -aq | wc -l),"
echo "\"psi_cpu_some_avg10\": \"$(awk '/^some/{print $2}' /proc/pressure/cpu | cut -d= -f2)\","
echo "\"psi_mem_some_avg10\": \"$(awk '/^some/{print $2}' /proc/pressure/memory | cut -d= -f2)\","
echo "\"snapshot_utc\": \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\""
echo "}"
